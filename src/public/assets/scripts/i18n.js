  let currentLang = 'es';
  const langSwitch = document.getElementById('langSwitch');
  const currentLangLabel = document.getElementById('currentLangLabel');

  function setLanguage(lang) {
    currentLang = lang;
    if (currentLangLabel) {
      currentLangLabel.textContent = lang.toUpperCase();
    }

    // Text translations
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (translations[lang] && translations[lang][key] !== undefined) {
        el.textContent = translations[lang][key];
      }
    });

    // Placeholder translations
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (translations[lang] && translations[lang][key] !== undefined) {
        el.setAttribute('placeholder', translations[lang][key]);
      }
    });

    // Alt, title and aria-label translations
    [['data-i18n-alt', 'alt'], ['data-i18n-title', 'title'], ['data-i18n-aria-label', 'aria-label']].forEach(([dataAttr, attr]) => {
      document.querySelectorAll(`[${dataAttr}]`).forEach(el => {
        const key = el.getAttribute(dataAttr);
        if (translations[lang] && translations[lang][key] !== undefined) {
          el.setAttribute(attr, translations[lang][key]);
        }
      });
    });

    // Update HTML lang attribute
    document.documentElement.lang = lang;
  }

  if (langSwitch) {
    langSwitch.addEventListener('click', () => {
      const nextLang = currentLang === 'es' ? 'en' : 'es';
      setLanguage(nextLang);
    });
    // El botón solo se muestra si este script funciona (ver styles.css)
    document.documentElement.classList.add('i18n-ready');
  }

